import { readStatementPhoto, type OcrLine } from '@/domain/bankStatement/photo';
import type { StatementResult } from '@/domain/bankStatement/read';

/** سطرٌ بعرضه من طول نصه (عشر نقاطٍ للحرف) كما في tests/d6.bankStatementPhoto.test.ts */
const ln = (text: string, left: number, top: number): OcrLine => ({ text, left, top, width: text.length * 10, height: 20 });
const view = (r: StatementResult) => (r.ok ? { lines: r.lines.map((l) => [l.date, l.amount]), closing: r.closing } : r.error);

// عربي من اليمين: الهجري 900، الميلادي 780، البيان (لا يُقرأ)، المبلغ 300، الرصيد 60 · والافتتاحي من رأس الكشف (العربي لا يُقرأ)
const rtl = (hijri: boolean): OcrLine[] => [
  ...(hijri ? [ln('1448/04/19', 900, 100)] : []), ln('01/10/2026', 780, 100), ln('500.00', 300, 100), ln('1,500.00', 60, 100),
  ...(hijri ? [ln('1448/04/21', 900, 140)] : []), ln('03/10/2026', 780, 140), ln('10.00', 300, 140), ln('1,490.00', 60, 140),
];
// إنجليزي من اليسار: «Date (H)» ثم «Date (G)»
const ltr = (hijri: boolean): OcrLine[] => [
  ln('Opening Balance', 40, 60), ln('1,000.00', 880, 60),
  ...(hijri ? [ln('19/04/1448', 40, 100)] : []), ln('01/10/2026', 160, 100), ln('TRANSFER IN', 300, 100), ln('500.00', 700, 100), ln('1,500.00', 880, 100),
  ...(hijri ? [ln('21/04/1448', 40, 140)] : []), ln('03/10/2026', 160, 140), ln('FEE', 300, 140), ln('10.00', 600, 140), ln('1,490.00', 880, 140),
  ln('Closing Balance', 40, 180), ln('1,490.00', 880, 180),
];
const want = { lines: [['2026-10-01', 50000], ['2026-10-03', -1000]], closing: 149000 };

describe('D2-7 · [متوسط] صورة كشفٍ بتاريخين هجري وميلادي: يُؤخذ الهجري تاريخاً فلا يُقرأ شيء (photo.ts:104-106)', () => {
  test('الضابط: الصفحتان بلا العمود الهجري تُقرآن', () => {
    expect([view(readStatementPhoto(rtl(false), { opening: 100000 })), view(readStatementPhoto(ltr(false)))]).toEqual([want, want]);
  });

  test('عربيٌّ من اليمين (الهجري أول الأعمدة): الحركتان بتاريخيهما الميلاديين', () => {
    // (الواقع: 'empty')
    expect(view(readStatementPhoto(rtl(true), { opening: 100000 }))).toEqual(want);
  });

  test('إنجليزيٌّ من اليسار و«Date (H)» أول الأعمدة: كذلك', () => {
    // (الواقع: 'empty')
    expect(view(readStatementPhoto(ltr(true)))).toEqual(want);
  });
});
