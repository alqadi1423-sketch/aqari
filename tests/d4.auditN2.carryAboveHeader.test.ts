import { readStatementGrid, type StatementResult } from '@/domain/bankStatement/read';
import { gridFromPdfItems } from '@/domain/bankStatement/pdfTable';

const view = (r: StatementResult) => (r.ok ? { amounts: r.lines.map((l) => l.amount), opening: r.opening, closing: r.closing } : r.error + ':' + r.detail);
const want = { amounts: [100000, 50000, -20000], opening: 500000, closing: 630000 };

const H = ['التاريخ', 'البيان', 'مدين', 'دائن', 'الرصيد'];
const rows = [
  ['01/10/2026', 'حوالة واردة مصطنعة', '', '1,000.00', '6,000.00'],
  ['02/10/2026', 'حوالة واردة مصطنعة ثانية', '', '500.00', '6,500.00'],
  ['05/10/2026', 'شراء مصطنع', '200.00', '', '6,300.00'],
];
const carry = ['', 'رصيد سابق', '', '', '6,300.00'];
const closing = ['', 'الرصيد الختامي', '', '', '6,300.00'];

const at = (str: string, x: number, y: number) => ({ str, x, y, size: 9 });
const head = (y: number) => [at('Date', 40, y), at('Description', 120, y), at('Debit', 300, y), at('Credit', 380, y), at('Balance', 460, y)];
const pdf = [[
  at('Statement Period: 01/10/2026 - 31/10/2026', 40, 760), ...head(700),
  at('01/10/2026', 40, 680), at('SALARY (synthetic)', 120, 680), at('1,000.00', 380, 680), at('6,000.00', 460, 680),
  at('02/10/2026', 40, 665), at('TRANSFER IN (synthetic)', 120, 665), at('500.00', 380, 665), at('6,500.00', 460, 665),
  at('05/10/2026', 40, 650), at('POS PURCHASE (synthetic)', 120, 650), at('200.00', 300, 650), at('6,300.00', 460, 650),
], [
  at('Previous Balance', 120, 730), at('6,300.00', 460, 730),
  ...head(700),
  at('Closing Balance', 120, 600), at('6,300.00', 460, 600),
]];

describe('N2-3 · [متوسط] الرصيد المنقول فوق صفّ العناوين المكرَّر في الصفحة الأخيرة يصير افتتاحيَّ الكشف فيُرفض كشفٌ صحيح (read.ts:219-220 و332)', () => {
  test('الضابط (H2-6): المنقول تحت صفّ العناوين المكرَّر يُقرأ', () => {
    expect(view(readStatementGrid([H, ...rows, H, carry, closing]))).toEqual(want);
  });

  test('المنقول «رصيد سابق» فوق صفّ العناوين المكرَّر: يُقرأ كذلك', () => {
    // (الواقع: 'balance:opening')
    expect(view(readStatementGrid([H, ...rows, carry, H, closing]))).toEqual(want);
  });

  test('وكذلك PDF: «Previous Balance» أعلى الصفحة الثانية فوق العناوين', () => {
    // (الواقع: 'balance:opening')
    expect(view(readStatementGrid(gridFromPdfItems(pdf)))).toEqual(want);
  });
});
