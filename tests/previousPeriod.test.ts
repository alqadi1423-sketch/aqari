import { previousPeriod } from '@/domain/periods';

test.each([
  ['2024-01-01', '2024-12-31', '2023-01-01', '2023-12-31'],
  ['2024-01-01', '2024-03-31', '2023-10-01', '2023-12-31'],
  ['2024-04-01', '2024-06-30', '2024-01-01', '2024-03-31'],
  ['2024-03-01', '2024-03-31', '2024-02-01', '2024-02-29'],
  ['2025-03-01', '2025-05-31', '2024-12-01', '2025-02-28'],
  ['2024-03-05', '2024-03-10', '2024-02-28', '2024-03-04'],
])('من %s إلى %s: المقابلة من %s إلى %s', (from, to, pf, pt) => {
  expect(previousPeriod(from, to)).toEqual({ from: pf, to: pt });
});
