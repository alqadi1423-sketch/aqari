/**
 * المراجعة الشاملة 2026-11-13 · E-14 · منخفض · المبلغ بالحروف ليس نحوياً في الآحاد والهللات.
 * قرار المالك «٤.١٣ المبلغ بالحروف صحيح نحوياً» (2026-10-05) وس١٤ («ريالان، ثلاثة ريالات، ثلاث هللات»).
 * السيناريو: سند قبضٍ بـ 1.00 يُكتب «واحد ريال»، و3.00 «ثلاثة ريال»، و11.00 «أحد عشر ريال»، و3.03 «… وثلاثة هللة»،
 * و0.56 «ستة وخمسون هللة».
 * الصحيح: المعدود بعدده: «ريال واحد · ريالان · ثلاثة ريالات · أحد عشر ريالاً · مئة ريال»، والهللة مؤنثة:
 * «هللة واحدة · هللتان · ثلاث هللات · إحدى عشرة هللة · ست وخمسون هللة» · والمرتبة مضافةٌ إلى الريال («ألف ريال · ألفا ريال»).
 */
import { moneyToArabicWords } from '@/domain/numberWords';

const w = (riyals: number, hal = 0) => moneyToArabicWords(riyals * 100 + hal).replace(/ فقط لا غير$/, '');

test.each([
  [1, 'ريال واحد'],
  [2, 'ريالان'],
  [3, 'ثلاثة ريالات'],
  [10, 'عشرة ريالات'],
  [11, 'أحد عشر ريالاً'],
  [25, 'خمسة وعشرون ريالاً'],
  [99, 'تسعة وتسعون ريالاً'],
  [100, 'مئة ريال'],
  [103, 'مئة وثلاثة ريالات'],
  [150, 'مئة وخمسون ريالاً'],
  [1000, 'ألف ريال'],
  [3000, 'ثلاثة آلاف ريال'],
  [4250, 'أربعة آلاف ومئتان وخمسون ريالاً'],
])('E-14 %i ريال ← %s', (n, words) => {
  expect(w(n)).toBe(words);
});

test.each([
  [1, 'هللة واحدة'],
  [2, 'هللتان'],
  [3, 'ثلاث هللات'],
  [8, 'ثماني هللات'],
  [10, 'عشر هللات'],
  [11, 'إحدى عشرة هللة'],
  [12, 'اثنتا عشرة هللة'],
  [13, 'ثلاث عشرة هللة'],
  [21, 'إحدى وعشرون هللة'],
  [22, 'اثنتان وعشرون هللة'],
  [50, 'خمسون هللة'],
  [56, 'ست وخمسون هللة'],
])('E-14 %i هللة ← %s', (n, words) => {
  expect(w(0, n)).toBe(words);
});

test('E-14 الريال والهللة معاً', () => {
  expect(w(3, 3)).toBe('ثلاثة ريالات وثلاث هللات');
  expect(w(1234, 56)).toBe('ألف ومئتان وأربعة وثلاثون ريالاً وست وخمسون هللة');
  expect(moneyToArabicWords(0)).toBe('صفر ريال فقط لا غير');
});

// المدقق المستقل للمرحلة ٣: المرتبة قبل «ريال» مضافةٌ إليه (س١٤ «الصيغة النحوية التامة»): «ألف ريال» لا «ألفاً ريال»، و«ألفا ريال»
// لا «ألفان ريال»، و«مئتا ريال» لا «مئتان ريال» · وما بعدها عددٌ يبقى كما كان («ألفان ومئة ريال»)
test.each([
  [11000, 'أحد عشر ألف ريال'],
  [50000, 'خمسون ألف ريال'],
  [115000, 'مئة وخمسة عشر ألف ريال'],
  [2000, 'ألفا ريال'],
  [200, 'مئتا ريال'],
  [202000, 'مئتا ألف وألفا ريال'],
  [2000000, 'مليونا ريال'],
  [15000000, 'خمسة عشر مليون ريال'],
  [2000000000, 'مليارا ريال'],
  [20000000000, 'عشرون مليار ريال'],
  [2100, 'ألفان ومئة ريال'],
  [1200, 'ألف ومئتا ريال'],
  [3000, 'ثلاثة آلاف ريال'],
])('E-14 المرتبة مضافةً إلى الريال %i ← %s', (n, words) => {
  expect(moneyToArabicWords(n * 100)).toBe(words + ' فقط لا غير');
});
