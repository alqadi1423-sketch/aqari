describe('U٢٦ · ترتيب القيد في اليوم الواحد بحثٌ تربيعي (solve)، والقراءة متزامنة على خيط الواجهة (app/bankStatement.tsx readFile)', () => {
  test('12,000 حركة في يومٍ واحد مطبوعةٌ من الأحدث: نحو 12 ثانية على Node (والمرتّبة نفسها أقل من ثانية)', () => {
    const rows: string[][] = [['الرصيد الافتتاحي', '0.00'], ['التاريخ', 'البيان', 'المبلغ', 'الرصيد']];
    for (let i = 12000; i >= 1; i--) rows.push(['2026/10/05', 'حركة مصطنعة ' + i, '1.00', i.toFixed(2)]);
    const t0 = Date.now();
    const r = readStatementGrid(rows);
    const ms = Date.now() - t0;
    expect(r.ok).toBe(true);
    // الصحيح: ترتيبٌ خطي (بالرصيد المطبوع: السطر التالي هو الذي رصيده = السابق ± مبلغه، بفهرسٍ لا بمسحٍ متكرر)
    expect(ms).toBeLessThan(4000);
  });
});
