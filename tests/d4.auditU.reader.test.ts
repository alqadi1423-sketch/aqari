describe('U٥ · CSV: علامة اقتباسٍ لا تُغلق تبتلع بقية الملف، وما لا يُقرأ مبلغاً يصير صفراً، ويُقبل الكشف مبتوراً', () => {
  test('ثلاث حركات تُقرأ حركتين (الثانية صفرٌ بيانها بقية الملف)', () => {
    const csv = 'Date,Description,Debit,Credit,Balance\n2026-10-01,Deposit,,100.00,1100.00\n2026-10-02,"Card,40.00,,1060.00\n2026-10-03,Fee,10.00,,1050.00\n';
    const r = readStatementFile({ name: 'synthetic.csv', bytes: new TextEncoder().encode(csv) });
    // الصحيح: اقتباسٌ مفتوح عند نهاية الملف خطأ صيغة · أو تُقرأ الحركات الثلاث بختامي 1,050
    if (r.ok) {
      expect(amounts(r)).toEqual([10000, -4000, -1000]);
      expect(r.closing).toBe(105000);
    } else expect(r.error).toBe('format');
  });
});

