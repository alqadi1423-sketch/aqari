describe('U٨ · MT940: تاريخ القيد (MMDD) يأخذ سنة تاريخ القيمة، فالحركة عند رأس السنة تُؤرَّخ قبل الكشف بسنة', () => {
  test(':61:2612310102 (قيمة 31 ديسمبر 2026، قيد 2 يناير) تُقرأ 2026-01-02', () => {
    const m = parseMt940([':20:SYN0001', ':25:SA0000000000000000000009', ':60F:C261201SAR0,00',
      ':61:2612310102C100,00NTRF//SYN1', ':86:حوالة مصطنعة', ':62F:C270131SAR100,00'].join('\n'));
    expect(m.lines[0].date).toBe('2027-01-02');
    // ونتيجة القارئ تمرّ بفحص الختامي (لا يفحص التاريخ) فتُحفظ بفترة 2026-01-02 وحدها
    const r = readStatementFile({ name: 'synthetic.sta', bytes: new TextEncoder().encode([':60F:C261201SAR0,00',
      ':61:2612310102C100,00NTRF//SYN1', ':86:x', ':62F:C270131SAR100,00'].join('\n')) });
    expect(r.ok && [r.from, r.to]).toEqual(['2027-01-02', '2027-01-02']);
  });
});

describe('U٩ · القاموس بلا «ال» التعريف: «المدين» و«الدائن» و«السحب» و«الإيداع» لا تُعرف، ولا تصحيح للتخمين في الشاشة', () => {
  test('roleOf وكشفٌ بعناوين معرّفة', () => {
    expect(['المدين', 'الدائن', 'السحب', 'الإيداع', 'المبلغ المدين'].map(roleOf)).toEqual(['debit', 'credit', 'debit', 'credit', 'debit']);
    const r = readStatementGrid([
      ['الرصيد الافتتاحي', '1,000.00'],
      ['التاريخ', 'البيان', 'المدين', 'الدائن', 'الرصيد'],
      ['2026/10/01', 'حوالة مصطنعة', '', '100.00', '1,100.00'],
    ]);
    expect(amounts(r)).toEqual([10000]);
  });

  test('الشاشة لا تعرض الأعمدة المخمَّنة ولا تتيح تصحيحها (قرار المالك 2026-10-09: «المستخدم يؤكد أو يصحح التخمين أول مرة»)', () => {
    const src = readFileSync(join(__dirname, '..', 'app', 'bankStatement.tsx'), 'utf8');
    // الربط يُمرَّر للقارئ من المحفوظ وحده (statementMapping)، والمعاينة لا تذكر أدوار الأعمدة (mapping.roles) ولا يبنيها المستخدم
    expect(src).toMatch(/mapping\.roles|roles\s*[:=]/);
  });
});

