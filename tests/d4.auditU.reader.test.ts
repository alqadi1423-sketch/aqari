describe('U١١ · CSV بترميز Windows-1256 (حفظ Excel العربي «CSV» الافتراضي) لا يُقرأ', () => {
  test('العناوين العربية تصير رموزاً تالفة فـ«لم تُعرف أعمدة الكشف»', () => {
    // 'التاريخ,البيان,مدين,دائن,الرصيد\n2026/10/01,إيداع,,100.00,1100.00\n2026/10/02,رسوم,10.00,,1090.00\n' بترميز cp1256
    const hex = 'c7e1cac7d1edce2cc7e1c8edc7e42ce3cfede42ccfc7c6e42cc7e1d1d5edcf0a323032362f31302f30312cc5edcfc7da2c2c3130302e30302c313130302e30300a'
      + '323032362f31302f30322cd1d3e6e32c31302e30302c2c313039302e30300a';
    const r = readStatementFile({ name: 'synthetic-ansi.csv', bytes: Uint8Array.from(Buffer.from(hex, 'hex')) }, { opening: 100000 });
    expect(amounts(r)).toEqual([10000, -1000]);
    expect(r.ok && r.lines[0].descr).toBe('إيداع');
  });
});

