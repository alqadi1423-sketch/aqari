import * as fs from 'node:fs';
import * as path from 'node:path';
import { UpgradeBackupError } from '@/domain/backup/upgrade';

test('رسالة فشل نسخة ما قبل الترقية لا تقول «نسخة كاملة» بعد قرار س٣', () => {
  expect(new UpgradeBackupError('سبب مصطنع').message).not.toMatch(/نسخة كاملة/);
});

test('رسالة إلغاء نسخة ما قبل الترقية في البوابة لا تقول «نسخة كاملة» بعد قرار س٣', () => {
  const src = fs.readFileSync(path.join(__dirname, '..', 'src/ui/UpgradeGate.tsx'), 'utf8');
  // النصوص الظاهرة وحدها (بين علامتي تنصيص) لا التعليقات
  const shown = [...src.matchAll(/'([^'\n]*)'/g)].map((m) => m[1]).filter((s) => /[؀-ۿ]/.test(s));
  expect(shown.filter((s) => /نسخة كاملة/.test(s))).toEqual([]);
});
