/**
 * المدقق الخارجي V · الجولة الحادية عشرة · صورة كشف البنك (src/domain/bankStatement/photo.ts · U١٢): سطور قارئ النص كما يُخرجها
 * ML Kit لصورٍ مصطنعة بشكل الكشوف الإنجليزية · كل اختبارٍ يسقط على الشيفرة الحالية ويصف السلوك الصحيح · بياناتٌ مصطنعة كلها.
 *   TZ=Asia/Riyadh npx jest tests/d4.auditV.photo.test.ts
 */
import { readStatementPhoto, type OcrLine } from '@/domain/bankStatement/photo';

/** سطرٌ بعرضه من طول نصه (عشر نقاطٍ للحرف) */
const ln = (text: string, left: number, top: number): OcrLine => ({ text, left, top, width: text.length * 10, height: 20 });

describe('V٣ · [عالٍ] حركةٌ في بيانها «FROM» تُعامَل صفَّ «الفترة» فتسقط من الصورة، وفي آخر الصفحة يُقبل الكشف بختاميٍّ ناقص (photo.ts:84)', () => {
  // readStatementPhoto يسأل summaryOf عن كلمات الصف قبل أن ينظر في تاريخه: «from» من كلمات «period» في القاموس، فـ«TRANSFER FROM …»
  // (أشيع بيانٍ للحوالة الواردة) يُدفع إلى ذيل الجدول كصفّ ملخص، ونوع «period» يُهمله القارئ العام · فالحركة تختفي: في وسط الصفحة
  // يُرفض كشفٌ صحيح، وفي آخرها (صورة صفحةٍ أولى بلا ختامي) يُقبل الكشف بلا الحوالة وختاميه أنقص منها، بلا تنبيه
  test('صفحةٌ أولى بلا ختامي، آخرها حوالةٌ واردة 400: ثلاث حركاتٍ وختامي 3,250', () => {
    const page: OcrLine[] = [
      ln('Date Description Debit Credit Balance', 40, 60),
      ln('Opening Balance', 40, 80), ln('2,000.00', 880, 80),
      ln('02/10/2026', 40, 100), ln('POS PURCHASE', 200, 100), ln('150.00', 560, 100), ln('1,850.00', 880, 100),
      ln('03/10/2026', 40, 140), ln('SALARY', 200, 140), ln('1,000.00', 720, 140), ln('2,850.00', 880, 140),
      ln('04/10/2026', 40, 180), ln('TRANSFER FROM 0012', 200, 180), ln('400.00', 720, 180), ln('3,250.00', 880, 180),
      ln('Page 1 of 2', 40, 260),
    ];
    const r = readStatementPhoto(page);
    // الصحيح: صفٌّ فيه تاريخٌ ومبلغ حركةٍ ورصيد حركةٌ ولو حمل بيانه كلمةً من قاموس الملخص
    expect(r.ok && r.lines.map((l) => l.amount)).toEqual([-15000, 100000, 40000]);
    expect(r.ok && r.closing).toBe(325000);
  });
});

describe('V١٢ · [متوسط] «الافتتاحي … الختامي …» في سطرٍ واحد من الصورة يأخذ الافتتاحيَّ قيمةَ الختامي فيُرفض كشفٌ صحيح (photo.ts:86)', () => {
  // صفّ الملخص في الصورة يُختصر إلى [كلماته، آخر مبلغٍ فيه]: «Opening Balance 2,000.00 Closing Balance 3,250.00» (مربع الملخص أعلى
  // الكشف بزوجين جنباً إلى جنب) يصير الافتتاحي 3,250 والختامي لا شيء، فيسقط التسلسل «balance» بلا عرضٍ للحفظ غير المتحقَّق
  test('الملخص بزوجين في سطر: الافتتاحي 2,000 والختامي 3,250، والحركتان بإشارتيهما', () => {
    const page: OcrLine[] = [
      ln('Opening Balance', 40, 20), ln('2,000.00', 260, 20), ln('Closing Balance', 520, 20), ln('3,250.00', 880, 20),
      ln('Date Description Debit Credit Balance', 40, 60),
      ln('02/10/2026', 40, 100), ln('POS PURCHASE', 200, 100), ln('150.00', 560, 100), ln('1,850.00', 880, 100),
      ln('03/10/2026', 40, 140), ln('SALARY', 200, 140), ln('1,400.00', 720, 140), ln('3,250.00', 880, 140),
    ];
    const r = readStatementPhoto(page);
    // الصحيح: كل كلمة ملخصٍ بالمبلغ الذي يليها في الصف (كما يفعل noteSummary في الجدول)
    expect(r.ok && [r.opening, r.closing, r.lines.map((l) => l.amount)]).toEqual([200000, 325000, [-15000, 140000]]);
  });
});
