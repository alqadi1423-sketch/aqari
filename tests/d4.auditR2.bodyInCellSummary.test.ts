import { readStatementGrid, type StatementResult } from '@/domain/bankStatement/read';

const view = (r: StatementResult) => (r.ok
  ? { ok: true, amounts: r.lines.map((l) => l.amount), opening: r.opening, closing: r.closing, warnings: r.warnings }
  : { ok: false, error: r.error });
const want = { ok: true, amounts: [100000, -50000], opening: 500000, closing: 550000, warnings: [] };

const H = ['Date', 'Description', 'Debit', 'Credit', 'Balance'];
const rows = [
  ['01/10/2026', 'RENT DEPOSIT (synthetic)', '', '1,000.00', '6,000.00'],
  ['03/10/2026', 'SERVICE FEES (synthetic)', '500.00', '', '5,500.00'],
];

describe('R2-1 · [متوسط] ملخصٌ بصفٍّ واحد قيمه في خلايا كلماته تحت العناوين يُسقط أول حركةٍ «صفَّ قيم» (read.ts:251-273)', () => {
  test('الضابط: الملخص نفسه بكلمةٍ واحدة في كل صف يُقرأ', () => {
    expect(view(readStatementGrid([H, ['', 'Opening Balance 5,000.00', '', '', ''], ...rows, ['', 'Closing Balance 5,500.00', '', '', '']]))).toEqual(want);
  });

  test('أ) «Closing Balance 5,500.00 | … | Opening Balance 5,000.00» فوق أول حركة: لا يسقط الإيداع', () => {
    // (الواقع: { ok: true, amounts: [-50000], opening: 600000, closing: 550000, warnings: [] })
    expect(view(readStatementGrid([H, ['', 'Closing Balance 5,500.00', '', '', 'Opening Balance 5,000.00'], ...rows]))).toEqual(want);
  });

  test('ب) «الرصيد الافتتاحي: 5,000.00 | … | الرصيد الختامي: 5,500.00» فوق أول حركة: لا يُرفض الكشف السليم', () => {
    // (الواقع: { ok: false, error: 'balance' })
    expect(view(readStatementGrid([H, ['', 'الرصيد الافتتاحي: 5,000.00', '', '', 'الرصيد الختامي: 5,500.00'], ...rows]))).toEqual(want);
  });
});
