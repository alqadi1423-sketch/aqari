import { buildInvoiceDoc, type CompanyInfo } from '@/domain/printDocs';

const CO_OFF: CompanyInfo = { name: 'منشأة مصطنعة', vatno: '300000000000003', cr: '', phone: '', address: '', vatEnabled: false };
const DOC = {
  no: 'INV-2026-0001', customerName: 'عميل مصطنع', customerVat: '', issue: '2026-01-05', due: '2026-01-05', notes: '',
  subtotalHalalas: 1_000_000, taxHalalas: 150_000, totalHalalas: 1_150_000,
  lines: [{ descr: 'إيجار مكتب', qty: 1, priceHalalas: 1_000_000, taxPct: 15 }],
};

describe('E-6 · [متوسط] الفاتورة الضريبية تُطبع بغير ما صدرت بعد تبديل مفتاح الضريبة', () => {
  test.failing('فاتورةٌ ضريبتها 1,500 تُطبع ضريبيةً بسطر ضريبتها ولو أُطفئ المفتاح بعدها', () => {
    const html = buildInvoiceDoc(CO_OFF, DOC, '13/11/2026 10:00');
    // (الواقع: العنوان «فاتورة» ولا «ضريبة القيمة المضافة» ولا «1,500.00» في الورقة، والإجمالي 11,500.00)
    expect(html).toContain('فاتورة ضريبية');
    expect(html).toContain('ضريبة القيمة المضافة');
    expect(html).toContain('1,500.00');
  });
});
