import { readStatementGrid, type StatementResult } from '@/domain/bankStatement/read';

const GRID = [
  ['Opening Balance', '0.00'],
  ['Date', 'Description', 'Debit', 'Credit', 'Balance'],
  ['01/10/2026', 'RENT TRANSFER (synthetic)', '', '2,500.00', '2,500.00'],
  ['01/11/2026', 'RENT TRANSFER (synthetic)', '', '2,500.00', '5,000.00'],
  ['01/12/2026', 'RENT TRANSFER (synthetic)', '', '2,500.00', '7,500.00'],
  ['Closing Balance', '7,500.00'],
];
const view = (r: StatementResult) => (r.ok ? { dates: r.lines.map((l) => l.date), order: r.mapping.dateOrder } : r.error + ':' + r.detail);

describe('H2-7 · [متوسط] صيغة التاريخ المصحَّحة في «أعمدة الكشف» لا تُقرأ بها التواريخ: يغلبها التخمين الأقصر مدىً (read.ts:178 و193-194)', () => {
  test('التخمين بلا ربط: «mdy» (تواريخ يناير) فتعرضه الورقة ليُصحَّح', () => {
    expect(view(readStatementGrid(GRID))).toEqual({ dates: ['2026-01-10', '2026-01-11', '2026-01-12'], order: 'mdy' });
  });

  test('بالربط المصحَّح «dmy»: التواريخ 1 أكتوبر و1 نوفمبر و1 ديسمبر، والربط «dmy»', () => {
    const guess = readStatementGrid(GRID);
    if (!guess.ok) throw new Error('لم يُقرأ: ' + guess.error); // i18n-exempt: رسالة اختبار
    // كما يبنيه confirmMapping في app/bankStatement.tsx:192
    const mapping = { ...guess.mapping, dateOrder: 'dmy' as const };
    // (الواقع: { dates: ['2026-01-10', '2026-01-11', '2026-01-12'], order: 'mdy' })
    expect(view(readStatementGrid(GRID, { mapping }))).toEqual({ dates: ['2026-10-01', '2026-11-01', '2026-12-01'], order: 'dmy' });
  });
});
