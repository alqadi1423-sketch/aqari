import { readStatementGrid, type StatementResult } from '@/domain/bankStatement/read';

const view = (r: StatementResult) => (r.ok ? { amounts: r.lines.map((l) => l.amount), opening: r.opening, closing: r.closing } : r.error + ':' + r.detail);
const want = { amounts: [50000, -1000], opening: 100000, closing: 149000 };

describe('D2-10 · [متوسط] عنوانٌ مدموج «المبلغ» فوق «مدين | دائن» يُسقط الإيداعات ويُرفض الكشف (read.ts:101-111 و218-225)', () => {
  test('الضابط: العناوين في صفٍّ واحد تُقرأ', () => {
    expect(view(readStatementGrid([
      ['الرصيد الافتتاحي', '1,000.00'],
      ['التاريخ', 'البيان', 'مدين', 'دائن', 'الرصيد'],
      ['01/10/2026', 'حوالة واردة مصطنعة', '', '500.00', '1,500.00'],
      ['03/10/2026', 'رسوم مصطنعة', '10.00', '', '1,490.00'],
      ['الرصيد الختامي', '1,490.00'],
    ]))).toEqual(want);
  });

  test('عربي: «التاريخ | البيان | المبلغ ‹مدموج› | الرصيد» ثم «مدين | دائن»', () => {
    // (الواقع: 'balance:opening')
    expect(view(readStatementGrid([
      ['الرصيد الافتتاحي', '1,000.00'],
      ['التاريخ', 'البيان', 'المبلغ', '', 'الرصيد'],
      ['', '', 'مدين', 'دائن', ''],
      ['01/10/2026', 'حوالة واردة مصطنعة', '', '500.00', '1,500.00'],
      ['03/10/2026', 'رسوم مصطنعة', '10.00', '', '1,490.00'],
      ['الرصيد الختامي', '1,490.00'],
    ]))).toEqual(want);
  });

  test('إنجليزي: «Date | Description | Amount (SAR) ‹merged› | Balance» ثم «Debit | Credit»', () => {
    expect(view(readStatementGrid([
      ['Opening Balance', '1,000.00'],
      ['Date', 'Description', 'Amount (SAR)', '', 'Balance'],
      ['', '', 'Debit', 'Credit', ''],
      ['01/10/2026', 'TRANSFER IN (synthetic)', '', '500.00', '1,500.00'],
      ['03/10/2026', 'SERVICE FEE (synthetic)', '10.00', '', '1,490.00'],
      ['Closing Balance', '1,490.00'],
    ]))).toEqual(want);
  });
});
