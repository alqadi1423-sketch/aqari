/**
 * المدقق H2 · الجولة السابعة عشرة · على 3f2c136 · صفّ «الفترة» الذي يطبع معها ما يوافقها بالهجري («الفترة من ٠١/١٠/٢٠٢٦ إلى ٣١/١٠/٢٠٢٦ الموافق
 * ١٩/٠٤/١٤٤٨ إلى ١٩/٠٥/١٤٤٨») لا يُقرأ فترةً أصلاً، فالتواريخ بلا سنة (شبيه ساب) لا تُقرأ، أو تأخذ سنتها من صفٍّ آخر فيه تاريخان («تاريخ فتح
 * الحساب … تاريخ الطباعة») · بياناتٌ مصطنعة كلها.
 *   TZ=Asia/Riyadh npx jest tests/d4.auditH2.hijriPeriod.test.ts
 *
 * H2-4 · متوسط · src/domain/bankStatement/read.ts:159-166 (الفترة من صفٍّ كل تواريخه الكاملة تُقرأ ميلادياً «ds.every(Boolean)»، والهجري سنته قبل 1990
 * فلا يُقرأ (normalize.ts:54) فيسقط الصف كله، ثم يُجرَّب ما بعده من الصفوف) مع read.ts:169-176 (yearFor: التاريخ بلا سنة يأخذ سنةً من طرفي
 * الفترة وحدهما):
 *  أ) كشف شبيه ساب (tests/d6.bankStatement.test.ts «تاريخٌ بلا سنةٍ من فترة الكشف») وصفّ فترته بالميلادي ومعه الهجري (في الخلية نفسها، أو في
 *     خليةٍ بعدها، أو بين قوسين بعد كل تاريخ): «empty» فلا يُقرأ شيء، والشاشة تعرض «أعمدة الكشف» ولا عمود خاطئ فيها يُصحَّح · وبلا الهجري يُقرأ.
 *  ب) ومع صفّ «Account Opening Date: 15/03/2015 | Print Date: 07/11/2026» في الرأس (U10): تصير الفترة 2015-03-15 إلى 2026-11-07 فيُقرأ «05/10»
 *     5 أكتوبر **2015** و«12/10» 12 أكتوبر 2015، ويُقرأ الكشف متحقَّقاً (التسلسل والختامي) بفترة أكتوبر 2015.
 * لماذا يهم: الكشوف السعودية تطبع الهجري بجانب الميلادي كثيراً (D2-7 وD2-8 في الصورة وفي عنوان العمود)، والفترة هي ما يعطي التاريخ بلا سنة
 * سنته · في (أ) كشفٌ صحيح لا يُقرأ ولا يملك المستخدم ما يصحّحه، وفي (ب) يُحفظ بصمت كشفٌ «متحقَّق» قبل إحدى عشرة سنة: لا يدخل تقرير أكتوبر
 * 2026، وإيداعاته تُقترح لها مطابقةٌ وتحصيلٌ بتواريخ 2015.
 * السلوك الصحيح: الهجري بجانب الميلادي ليس تاريخ الفترة (كـD2-7 وD2-8): الفترة 2026-10-01 إلى 2026-10-31 من تواريخها الميلادية، فيُقرأ الكشف
 * في (أ) و(ب) كما يُقرأ بلا الهجري.
 */
import { readStatementGrid, type StatementResult } from '@/domain/bankStatement/read';

const view = (r: StatementResult) => (r.ok ? { lines: r.lines.map((l) => [l.date, l.amount]), from: r.from, to: r.to } : r.error + ':' + r.detail);

describe('H2-4 · [متوسط] الهجري في صفّ «الفترة» يُسقط الفترة: التاريخ بلا سنة لا يُقرأ أو يُقرأ بسنة فتح الحساب (read.ts:159-176)', () => {
  // شبيه ساب: أرقامٌ هندية، والفاصل العشري «ﺭ»، وتاريخٌ بلا سنة، والافتتاحي من رأس الكشف
  const SABB_BODY = [
    ['التاريخ', 'الوصف', 'مدين', 'دائن', 'الرصيد'],
    ['١٠/٠٢', 'راتب مصطنع', '', '٨٠٠٠ﺭ٠٠', ''],
    ['١٠/٠٥', 'سداد مصطنع', '١٢٠٠ﺭ٥٠', '', '٩٧٩٩ﺭ٥٠'],
    ['١٠/٢٠', 'تحويل مصطنع', '٧٩٩ﺭ٥٠', '', ''],
    ['الرصيد الختامي', '', '', '', '٩٠٠٠ﺭ٠٠'],
  ];
  const sabb = { lines: [['2026-10-02', 800000], ['2026-10-05', -120050], ['2026-10-20', -79950]], from: '2026-10-01', to: '2026-10-31' };

  test('الضابط (أ): صفّ الفترة بالميلادي وحده يُقرأ', () => {
    expect(view(readStatementGrid([['الفترة من ٠١/١٠/٢٠٢٦ إلى ٣١/١٠/٢٠٢٦'], ...SABB_BODY], { opening: 300000 }))).toEqual(sabb);
  });

  test('(أ) والهجري معه في الخلية نفسها، أو في خليةٍ بعدها، أو بين قوسين: يُقرأ كما بدونه', () => {
    const rows = [
      ['الفترة من ٠١/١٠/٢٠٢٦ إلى ٣١/١٠/٢٠٢٦ الموافق ١٩/٠٤/١٤٤٨ إلى ١٩/٠٥/١٤٤٨'],
      ['الفترة من ٠١/١٠/٢٠٢٦ إلى ٣١/١٠/٢٠٢٦', 'الموافق ١٤٤٨/٠٤/١٩ - ١٤٤٨/٠٥/١٩'],
      ['الفترة من ٠١/١٠/٢٠٢٦ (١٩/٠٤/١٤٤٨هـ) إلى ٣١/١٠/٢٠٢٦ (١٩/٠٥/١٤٤٨هـ)'],
    ];
    // (الواقع: ['empty:undefined', 'empty:undefined', 'empty:undefined'])
    expect(rows.map((p) => view(readStatementGrid([p, ...SABB_BODY], { opening: 300000 })))).toEqual([sabb, sabb, sabb]);
  });

  test('الضابط (ب): «Account Opening Date … Print Date» مع صفّ فترةٍ ميلادي: تواريخ أكتوبر 2026', () => {
    const BODY = [
      ['Opening Balance', '5,000.00'],
      ['Date', 'Description', 'Debit', 'Credit', 'Balance'],
      ['05/10', 'TRANSFER IN (synthetic)', '', '500.00', '5,500.00'],
      ['12/10', 'SERVICE FEE (synthetic)', '10.00', '', '5,490.00'],
      ['Closing Balance', '', '', '', '5,490.00'],
    ];
    const r = readStatementGrid([['Statement Period: 01/10/2026 - 31/10/2026'], ['Account Opening Date: 15/03/2015', 'Print Date: 07/11/2026'], ...BODY]);
    expect(view(r)).toEqual({ lines: [['2026-10-05', 50000], ['2026-10-12', -1000]], from: '2026-10-01', to: '2026-10-31' });
  });

  test('(ب) والفترة بهجريها: لا تُؤرَّخ الحركات بسنة فتح الحساب 2015', () => {
    const BODY = [
      ['Opening Balance', '5,000.00'],
      ['Date', 'Description', 'Debit', 'Credit', 'Balance'],
      ['05/10', 'TRANSFER IN (synthetic)', '', '500.00', '5,500.00'],
      ['12/10', 'SERVICE FEE (synthetic)', '10.00', '', '5,490.00'],
      ['Closing Balance', '', '', '', '5,490.00'],
    ];
    const r = readStatementGrid([['Statement Period: 01/10/2026 - 31/10/2026 (19/04/1448 - 19/05/1448)'], ['Account Opening Date: 15/03/2015', 'Print Date: 07/11/2026'], ...BODY]);
    // (الواقع: { lines: [['2015-10-05', 50000], ['2015-10-12', -1000]], from: '2015-10-05', to: '2015-10-12' } مقروءاً متحقَّقاً)
    expect(view(r)).toEqual({ lines: [['2026-10-05', 50000], ['2026-10-12', -1000]], from: '2026-10-01', to: '2026-10-31' });
  });
});
