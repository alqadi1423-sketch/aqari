/**
 * الطبقة التي أُغلقت للانتقال إلى شاشة أخرى (D-4) · ورقة العقد تُغلق قبل «تحصيل» لأن الورقة نافذةٌ أصلية تبقى فوق
 * كل شاشة إن بقيت مفتوحة · فتُذكر هنا وتُفتح ثانيةً مرةً واحدة حين يعود التركيز إلى شاشتها.
 * قرار المالك 2026-09-09: «الرجوع يغلق الطبقة العليا وحدها، ويعيد ما تحتها بحالته».
 * خالصة بلا React لتُختبر وحدها · والخطّاف في returnLayer.ts.
 */
export class ReturnLayer<T> {
  private pending: T | null = null;

  /** تُذكر الطبقة قبل الانتقال · والمغادرة الأخيرة هي ما يعود */
  leave(v: T): void {
    this.pending = v;
  }

  /** ما يعود عند التركيز، مرةً واحدة · ثم لا شيء */
  take(): T | null {
    const v = this.pending;
    this.pending = null;
    return v;
  }
}
